const SPACE = 0.3, GAP = 0.12, MISSING: Glyph = { w: 0.4, s: [[0, 0, 0.4, 0, 0.4, 0.7, 0, 0.7, 0, 0]] };

/** 一行字的宽（em）。 */
export function textWidthEm(text: string): number {
  let w = 0;
  for (const ch of text) w += (ch === " " ? SPACE : (G[ch] ?? MISSING).w) + GAP;
  return Math.max(0, w - GAP);
}

/**
 * 一行字 → 线段（世界坐标，a b 成对）：左下角在 origin，往 right 排、往 up 长；em = 一个 em 多长（世界米）。
 * 折线拆成线段（辅助几何的线族吃线段）。
 */
export function strokeText(text: string, origin: Vec3, right: Vec3, up: Vec3, em: number): number[] {
  const out: number[] = [];
  let x = 0;
  const P = (u: number, v: number): [number, number, number] => [origin.x + (right.x * u + up.x * v) * em, origin.y + (right.y * u + up.y * v) * em, origin.z + (right.z * u + up.z * v) * em];
  for (const ch of text) {
    if (ch === " ") { x += SPACE + GAP; continue; }
    const g = G[ch] ?? MISSING;
    for (const s of g.s) for (let i = 0; i + 3 < s.length; i += 2) out.push(...P(x + s[i], s[i + 1]), ...P(x + s[i + 2], s[i + 3]));
    x += g.w + GAP;
  }
  return out;
}
